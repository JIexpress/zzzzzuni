#if UNITY_EDITOR
using System;
using System.Collections.Generic;
using System.IO;
using System.Text;
using UnityEditor;
using UnityEditor.SceneManagement;
using UnityEngine;

namespace Game.View.Editor
{
    /// <summary>
    /// TASK-A-R9-10 demo evidence: renders the committed SCN_Game through two
    /// capture cameras and writes
    /// - <c>Docs/Parity/demo_stage_playerview.png</c> — exactly the in-game
    ///   camera (0, 3.2, -4.2), i.e. what a player sees of the model stage;
    /// - <c>Docs/Parity/demo_stage_overview.png</c> — a three-quarter overview
    ///   framing the whole character ring (the facing/scale sanity shot);
    /// - <c>Docs/Parity/demo_stage_log.txt</c> — per-model measured final
    ///   bounds and applied scale (the size record of the task report).
    ///
    /// Batch (self-exits, like DemoBootFlow):
    ///   -executeMethod Game.View.Editor.StageScreenshot.RunFromCommandLine
    /// Requires the scene generated by GameSceneSetup (it opens it read-only
    /// from disk and never saves).
    /// </summary>
    public static class StageScreenshot
    {
        private const int kWidth = 1280;
        private const int kHeight = 720;
        private const string kOutDir = "Docs/Parity";

        /// <summary>Entry point: capture both shots + the size record. Self-exits.</summary>
        public static void RunFromCommandLine()
        {
            int exitCode;
            try
            {
                exitCode = Run();
            }
            catch (Exception error)
            {
                Debug.Log($"[StageScreenshot] EXCEPTION:\n{error}");
                exitCode = 1;
            }

            Debug.Log($"[StageScreenshot] done, exit={exitCode}");
            EditorApplication.Exit(exitCode);
        }

        private static int Run()
        {
            string repoRoot = Path.GetFullPath(Path.Combine(Application.dataPath, "..", ".."));
            Directory.CreateDirectory(Path.Combine(repoRoot, kOutDir));

            var scene = EditorSceneManager.OpenScene("Assets/Scenes/SCN_Game.unity", OpenSceneMode.Single);
            var report = new StringBuilder();
            report.AppendLine($"SCN_Game model stage record (TASK-A-R9-10) @ {DateTime.Now:yyyy-MM-dd HH:mm:ss}");
            report.AppendLine($"unity: {Application.unityVersion}  scene: {scene.path}");

            int captured = 0;
            captured += Capture(new Vector3(0f, 3.2f, -4.2f), Quaternion.Euler(10f, 0f, 0f), 60f,
                Path.Combine(repoRoot, kOutDir, "demo_stage_playerview.png"));
            captured += Capture(new Vector3(-12f, 10f, -12f), Quaternion.Euler(30f, 45f, 0f), 50f,
                Path.Combine(repoRoot, kOutDir, "demo_stage_overview.png"));

            // Facing calibration shots: from the ring centre outward at each
            // character (the player capsule's backfaces are culled, so the
            // camera at the centre sees through it). A correct
            // ForwardYawOffset shows the character's FRONT in its shot.
            foreach (ModelStageLayout.Placement character in ModelStageLayout.Characters)
            {
                GameObject root = GameObject.Find(character.Model);
                if (root == null)
                {
                    continue;
                }

                Vector3 head = root.transform.position + new Vector3(0f, 1.2f, 0f);
                captured += CaptureLook(new Vector3(0f, 1.5f, 0f), head, 55f,
                    Path.Combine(repoRoot, kOutDir, $"demo_stage_face_{character.Model}.png"));
            }

            // Duplicate models (trees/fence) share one scene name; record each
            // DISTINCT model once (the first instance) — the plan's count.
            var recorded = new HashSet<string>();
            foreach (ModelStageLayout.Placement placement in ModelStageLayout.All)
            {
                if (!recorded.Add(placement.Model))
                {
                    continue;
                }

                GameObject root = GameObject.Find(placement.Model);
                if (root == null)
                {
                    report.AppendLine($"{placement.Model,-30} MISSING IN SCENE");
                    recorded.Remove(placement.Model);
                    continue;
                }

                Bounds final = GameSceneSetupMeasureBounds(root);
                float scale = root.transform.localScale.x;
                report.AppendLine(
                    $"{placement.Model,-30} scale={scale:F4} finalSize=({final.size.x:F2}, {final.size.y:F2}, {final.size.z:F2}) " +
                    $"minY={final.min.y:F3} pos={root.transform.position:F2} yaw={root.transform.eulerAngles.y:F0}");
            }

            report.AppendLine($"placed={recorded.Count}/10  shots={captured}/6");

            File.WriteAllText(Path.Combine(repoRoot, kOutDir, "demo_stage_log.txt"),
                report.Replace("\r\n", "\n").ToString(), new UTF8Encoding(false));
            Debug.Log($"[StageScreenshot] report:\n{report}");

            return captured == 6 && recorded.Count == 10 ? 0 : 1;
        }

        /// <summary>Look-at variant of <see cref="Capture"/> (position → target).</summary>
        private static int CaptureLook(Vector3 position, Vector3 lookTarget, float fov, string pngPath)
        {
            Vector3 forward = (lookTarget - position).normalized;
            return Capture(position, Quaternion.LookRotation(forward, Vector3.up), fov, pngPath);
        }

        private static int Capture(Vector3 position, Quaternion rotation, float fov, string pngPath)
        {
            var camGo = new GameObject("~StageCaptureCam");
            try
            {
                Camera cam = camGo.AddComponent<Camera>();
                cam.transform.position = position;
                cam.transform.rotation = rotation;
                cam.fieldOfView = fov;
                cam.nearClipPlane = 0.1f;
                cam.farClipPlane = 200f;
                cam.clearFlags = CameraClearFlags.Skybox;

                var rt = new RenderTexture(kWidth, kHeight, 24, RenderTextureFormat.ARGB32);
                cam.targetTexture = rt;
                cam.Render();

                RenderTexture.active = rt;
                var tex = new Texture2D(kWidth, kHeight, TextureFormat.RGBA32, false);
                tex.ReadPixels(new Rect(0, 0, kWidth, kHeight), 0, 0);
                tex.Apply();
                RenderTexture.active = null;

                File.WriteAllBytes(pngPath, ImageConversion.EncodeToPNG(tex));
                UnityEngine.Object.DestroyImmediate(tex);
                rt.Release();

                bool ok = File.Exists(pngPath) && new FileInfo(pngPath).Length > 0;
                Debug.Log($"[StageScreenshot] {pngPath} {(ok ? "OK" : "FAILED")}");
                return ok ? 1 : 0;
            }
            finally
            {
                UnityEngine.Object.DestroyImmediate(camGo);
            }
        }

        /// <summary>Same bounds semantics as GameSceneSetup.MeasureBounds (skinned meshes via mesh bounds).</summary>
        private static Bounds GameSceneSetupMeasureBounds(GameObject root)
        {
            bool any = false;
            var bounds = new Bounds();
            foreach (Renderer renderer in root.GetComponentsInChildren<Renderer>(false))
            {
                var skinned = renderer as SkinnedMeshRenderer;
                Bounds part = skinned != null && skinned.sharedMesh != null
                    ? TransformBounds(skinned.sharedMesh.bounds, skinned.localToWorldMatrix)
                    : renderer.bounds;
                if (!any)
                {
                    bounds = part;
                    any = true;
                }
                else
                {
                    bounds.Encapsulate(part);
                }
            }

            return bounds;
        }

        private static Bounds TransformBounds(Bounds bounds, Matrix4x4 matrix)
        {
            var center = matrix.MultiplyPoint3x4(bounds.center);
            var extents = bounds.extents;
            var result = new Bounds(center, Vector3.zero);
            foreach (Vector3 axis in new[]
                     {
                         matrix.MultiplyVector(new Vector3(extents.x, 0f, 0f)),
                         matrix.MultiplyVector(new Vector3(0f, extents.y, 0f)),
                         matrix.MultiplyVector(new Vector3(0f, 0f, extents.z)),
                     })
            {
                result.Encapsulate(center + axis);
                result.Encapsulate(center - axis);
            }

            return result;
        }
    }
}
#endif
