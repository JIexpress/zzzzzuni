#if UNITY_EDITOR
using System;
using System.Text;

namespace ZFrame.Data.ConfigEditor
{
    /// <summary>
    /// Pure schema -> C# table-shell emitter (TASK-A-CONF-02). Emits the
    /// `XConfigTable : ConfigTable&lt;XConfigRow&gt;` shell so adding a table
    /// stays zero-hand-written code: the row type and its table class are
    /// both generated from the annotated CSV header. Deterministic output
    /// (same schema => byte-identical source); callers write via
    /// <see cref="ConfigRowCodegen.WriteIfChanged"/>.
    ///
    /// Naming convention (must stay aligned with
    /// <see cref="ConfigTableRegistry"/> and <see cref="CsvExporter.TableAssetPathFor"/>):
    ///   row   = Pascal(csv stem) + "ConfigRow"
    ///   table = Pascal(csv stem) + "ConfigTable"
    ///   asset = Assets/Configs/CFG_&lt;Pascal(stem)&gt;Table.asset
    /// </summary>
    public static class ConfigTableCodegen
    {
        /// <summary>Suffix shared by every generated table shell.</summary>
        public const string TableSuffix = "ConfigTable";

        /// <summary>Row-name suffix replaced when deriving the table name.</summary>
        private const string RowSuffix = "ConfigRow";

        /// <summary>Table class name for a row class name (WaveConfigRow -> WaveConfigTable).</summary>
        public static string TableClassNameForRow(string rowClassName)
        {
            if (string.IsNullOrEmpty(rowClassName))
            {
                return null;
            }

            var stem = rowClassName.EndsWith(RowSuffix, StringComparison.Ordinal)
                ? rowClassName.Substring(0, rowClassName.Length - RowSuffix.Length)
                : rowClassName;
            var name = stem + TableSuffix;
            return ConfigRowSchema.IsValidIdentifier(name) ? name : null;
        }

        /// <summary>Display stem used in fileName / menuName (WaveConfigTable -> Wave).</summary>
        public static string DisplayStemFor(string tableClassName)
        {
            return tableClassName.EndsWith(TableSuffix, StringComparison.Ordinal)
                ? tableClassName.Substring(0, tableClassName.Length - TableSuffix.Length)
                : tableClassName;
        }

        /// <summary>Emits the C# source of the table shell; throws on invalid input.</summary>
        public static string Generate(ConfigRowSchema schema)
        {
            if (schema == null)
            {
                throw new ArgumentNullException(nameof(schema));
            }

            if (!schema.IsValid)
            {
                throw new ArgumentException(
                    "schema 非法，拒绝生成坏代码: " + string.Join("; ", schema.Errors), nameof(schema));
            }

            var tableClassName = TableClassNameForRow(schema.RowClassName);
            if (tableClassName == null)
            {
                throw new ArgumentException(
                    $"行类名 '{schema.RowClassName}' 无法推导出合法表类名", nameof(schema));
            }

            var sourcePath = OneLine(schema.SourceCsvPath ?? "(unknown)");
            var stem = DisplayStemFor(tableClassName);
            var assetName = "CFG_" + stem + "Table"; // 与 CsvExporter.TableAssetPathFor 同约定
            var menuName = "ZFrame/CFG " + stem + " Table";

            var sb = new StringBuilder();
            sb.Append("// <auto-generated>\n");
            sb.Append("// 本文件由 ZFrame.Data.ConfigEditor.ConfigTableCodegen 从配置表 schema 自动生成，请勿手改。\n");
            sb.Append($"// 源表: {sourcePath}\n");
            sb.Append("// 重新生成: Unity 菜单 ZFrame/Config/生成行类型(全部) 或\n");
            sb.Append("//   -executeMethod ZFrame.Data.ConfigEditor.ConfigCodeGenerator.GenerateAllFromCommandLine\n");
            sb.Append("// </auto-generated>\n");
            sb.Append("using UnityEngine;\n");
            sb.Append('\n');
            sb.Append($"namespace {ConfigRowCodegen.RowNamespace}\n");
            sb.Append("{\n");
            sb.Append($"    /// <summary>Generated table shell for {OneLine(schema.RowClassName)}. Do not edit by hand.</summary>\n");
            sb.Append($"    [CreateAssetMenu(fileName = \"{assetName}\", menuName = \"{menuName}\")]\n");
            sb.Append($"    public class {tableClassName} : ConfigTable<{OneLine(schema.RowClassName)}>\n");
            sb.Append("    {\n");
            sb.Append("    }\n");
            sb.Append("}\n");
            return sb.ToString();
        }

        /// <summary>Flattens line breaks so a weird path cannot break out of the comment block.</summary>
        private static string OneLine(string text)
        {
            return text.Replace("\r", " ").Replace("\n", " ");
        }
    }
}
#endif
