// ConfigTableCodegenTests.cs —— 表类薄壳生成 + 注册自动化的 EditMode 单测（TASK-A-CONF-02）。
//
// 钉住五件事：
//   1) 生成器同批产出「行类型 + 表类薄壳」，同输入两次生成逐字节一致（可复现）
//   2) 入库产物（Enemy/Wave）与生成器当前输出逐字节同步（防漂移守卫）
//   3) 注册表靠反射发现，零手写：enemy / wave 都能按 csv 名解析到表类型
//   4) 全自动链路：放 CSV → 校验 → 生成 → 注册 → 建资产 → ConfigService 可读
//   5) 返工（2026-11-15）：全链路走**真菜单入口**且不传路径；既有资产不被清空

using System;
using System.Collections.Generic;
using System.IO;
using System.Text;
using NUnit.Framework;
using UnityEditor;
using UnityEngine;
using ZFrame.Data.Config;
using ZFrame.Data.ConfigEditor;

namespace ZFrame.Data.Tests
