        // ---- 5) 坏表头纪律：行类型与表类都不产出 ------------------------------------

        [Test]
        public void GenerateForRowType_BadHeader_WritesNeitherRowNorTable()
        {
            var dir = NewTempDir();
            var csvPath = Path.Combine(dir, "badtable.csv");
            File.WriteAllText(csvPath, "Id:string,Hp:intt\nslime,30\n", new UTF8Encoding(false));
            var outDir = Path.Combine(dir, "out");

            var report = ConfigCodeGenerator.GenerateForRowType(csvPath, outDir);

            Assert.IsFalse(report.Ok, "类型拼错必须报错");
            Assert.IsFalse(report.WroteFile);
            Assert.IsFalse(report.WroteTableFile);
            Assert.IsFalse(File.Exists(Path.Combine(outDir, "BadtableConfigRow.cs")), "坏表头不许产出坏代码");
            Assert.IsFalse(File.Exists(Path.Combine(outDir, "BadtableConfigTable.cs")), "坏表头连表类也不许产出");
        }

        [Test]
        public void TableClassNameForRow_FollowsConvention()
        {
            Assert.AreEqual("EnemyConfigTable", ConfigTableCodegen.TableClassNameForRow("EnemyConfigRow"));
            Assert.AreEqual("WaveConfigTable", ConfigTableCodegen.TableClassNameForRow("WaveConfigRow"));
            Assert.AreEqual("EnemyConfigTable", ConfigCodeGenerator.TableClassNameFor(EnemyCsv));
            Assert.AreEqual("EnemyConfigTable.cs", Path.GetFileName(ConfigCodeGenerator.TableSourcePathFor(EnemyCsv)));
        }
