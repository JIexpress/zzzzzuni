    public class ConfigTableCodegenTests
    {
        private const string WaveCsv = "Assets/Configs/CSV/wave.csv";
        private const string EnemyCsv = "Assets/Configs/CSV/enemy.csv";
        private const string GeneratedRoot = "Assets/ZFrame/Data/Config/Generated";
        private const string ImportMenu = "Assets/ZFrame/Import as Config Table";

        private readonly List<string> _tempDirs = new List<string>();
        private readonly List<string> _tempAssets = new List<string>();
        private UnityEngine.Object _savedSelection;

        [SetUp]
        public void SetUp()
        {
            _savedSelection = Selection.activeObject;
        }

        [TearDown]
        public void TearDown()
        {
            Selection.activeObject = _savedSelection;
            foreach (var assetPath in _tempAssets)
            {
                if (!string.IsNullOrEmpty(assetPath))
                {
                    AssetDatabase.DeleteAsset(assetPath);
                }
            }

            _tempAssets.Clear();
            foreach (var dir in _tempDirs)
            {
                if (Directory.Exists(dir))
                {
                    Directory.Delete(dir, true);
                }
            }

            _tempDirs.Clear();
        }

        private string NewTempDir()
        {
            var dir = Path.Combine(Path.GetTempPath(), "zframe-table-codegen", Guid.NewGuid().ToString("N"));
            Directory.CreateDirectory(dir);
            _tempDirs.Add(dir);
            return dir;
        }

        private static byte[] ReadAllBytes(string path)
        {
            return File.ReadAllBytes(path);
        }

        // ---- 1) 同批生成 + 可复现 --------------------------------------------------

        [Test]
        public void GenerateForRowType_EmitsRowAndTable_SecondRunIsByteIdentical()
        {
            var dir = NewTempDir();

            var first = ConfigCodeGenerator.GenerateForRowType(WaveCsv, dir);
            Assert.IsTrue(first.Ok, string.Join("; ", first.Errors));
            Assert.AreEqual("WaveConfigTable", first.TableClassName);
            Assert.IsTrue(first.WroteFile, "首次必须写出行类型");
            Assert.IsTrue(first.WroteTableFile, "首次必须写出表类薄壳");

            var rowPath = Path.Combine(dir, "WaveConfigRow.cs");
            var tablePath = Path.Combine(dir, "WaveConfigTable.cs");
            Assert.IsTrue(File.Exists(rowPath), "行类型文件必须落盘");
            Assert.IsTrue(File.Exists(tablePath), "表类文件必须落盘");

            var rowBytes = ReadAllBytes(rowPath);
            var tableBytes = ReadAllBytes(tablePath);
            var rowWriteTime = File.GetLastWriteTimeUtc(rowPath);
            var tableWriteTime = File.GetLastWriteTimeUtc(tablePath);

            var second = ConfigCodeGenerator.GenerateForRowType(WaveCsv, dir);
            Assert.IsTrue(second.Ok, string.Join("; ", second.Errors));
            Assert.IsFalse(second.WroteFile, "内容未变时不该重写行类型（避免 Unity 重编译 churn）");
            Assert.IsFalse(second.WroteTableFile, "内容未变时不该重写表类");

            CollectionAssert.AreEqual(rowBytes, ReadAllBytes(rowPath), "同输入两次生成必须逐字节一致");
            CollectionAssert.AreEqual(tableBytes, ReadAllBytes(tablePath), "表类同输入两次生成必须逐字节一致");
            Assert.AreEqual(rowWriteTime, File.GetLastWriteTimeUtc(rowPath), "内容未变时 mtime 不该动");
            Assert.AreEqual(tableWriteTime, File.GetLastWriteTimeUtc(tablePath), "内容未变时 mtime 不该动");
        }

        [Test]
        public void GenerateForRowType_EmitsAutoGeneratedMarkerAndCreateAssetMenu()
        {
            var dir = NewTempDir();
            ConfigCodeGenerator.GenerateForRowType(WaveCsv, dir);

            var tableText = File.ReadAllText(Path.Combine(dir, "WaveConfigTable.cs"), new UTF8Encoding(false));

            StringAssert.Contains("// <auto-generated>", tableText);
            StringAssert.Contains("源表: Assets/Configs/CSV/wave.csv", tableText);
            StringAssert.Contains("public class WaveConfigTable : ConfigTable<WaveConfigRow>", tableText);
            StringAssert.Contains("[CreateAssetMenu(fileName = \"CFG_WaveTable\", menuName = \"ZFrame/CFG Wave Table\")]",
                tableText);
        }

        // ---- 2) 入库产物同步守卫 ---------------------------------------------------

        [Test]
        public void CommittedArtifacts_MatchGeneratorOutput_ForEnemyAndWave()
        {
            var dir = NewTempDir();
            var report = ConfigCodeGenerator.GenerateForRowType(EnemyCsv, dir);
            Assert.IsTrue(report.Ok, string.Join("; ", report.Errors));
            CollectAndCompare(dir, "EnemyConfigRow.cs");
            CollectAndCompare(dir, "EnemyConfigTable.cs");

            var waveReport = ConfigCodeGenerator.GenerateForRowType(WaveCsv, dir);
            Assert.IsTrue(waveReport.Ok, string.Join("; ", waveReport.Errors));
            CollectAndCompare(dir, "WaveConfigRow.cs");
            CollectAndCompare(dir, "WaveConfigTable.cs");
        }

        private static void CollectAndCompare(string generatedDir, string fileName)
        {
            var generated = ReadAllBytes(Path.Combine(generatedDir, fileName));
            var committedPath = $"{GeneratedRoot}/{fileName}";
            Assert.IsTrue(File.Exists(committedPath), $"入库产物缺失: {committedPath}");
            CollectionAssert.AreEqual(generated, ReadAllBytes(committedPath),
                $"{fileName}: 入库产物与生成器输出不一致（改了 CSV 表头却没重新生成？）");
        }

        // ---- 3) 注册自动化（零手写注册行） ------------------------------------------

        [Test]
        public void Registry_DiscoversTablesByCsvName_WithoutHandRegistration()
        {
            Assert.IsTrue(ConfigTableRegistry.TryGetTableType("enemy.csv", out var enemy));
            Assert.AreEqual(typeof(EnemyConfigTable), enemy);

            Assert.IsTrue(ConfigTableRegistry.TryGetTableType("Assets/Configs/CSV/wave.csv", out var wave));
            Assert.AreEqual(typeof(WaveConfigTable), wave, "新表无需注册行即可被发现");

            Assert.AreEqual("wave", ConfigTableRegistry.KeyOf(typeof(WaveConfigTable)));
            Assert.AreEqual(typeof(WaveConfigRow), ConfigTableRegistry.FindRowType(typeof(WaveConfigTable)));
            Assert.AreEqual(typeof(WaveConfigTable),
                ConfigTableRegistry.FindTableTypeForRow(typeof(WaveConfigRow)));

            Assert.AreEqual(0, ConfigTableRegistry.Conflicts.Count, "注册键不应重复");
        }

        [Test]
        public void Registry_UnknownCsv_ReturnsFalse()
        {
            Assert.IsFalse(ConfigTableRegistry.TryGetTableType("npc_personality.csv", out var table));
            Assert.IsNull(table, "裸表头表（行类型在 Game.Domain）没有表类，不应被误注册");
            Assert.IsFalse(ConfigTableRegistry.TryGetTableType("", out _));
            Assert.IsFalse(ConfigTableRegistry.TryGetTableType(null, out _));
        }

        // ---- 4) 全自动链路：走真菜单入口，不传任何预规范化路径 ----------------------
        //
        // 返工前的假绿：旧用例自己传入 "Assets/Configs/__AutoTest_CFG_WaveTable.asset"，
        // 于是 CsvExporter.TableAssetPathFor 的默认解析分支从未被执行。现在 Selection 指向
        // csv、直接调 EditorApplication.ExecuteMenuItem，路径必须由产品代码自己算。

        /// <summary>Sets Selection to the csv and runs the real context-menu entry.</summary>
        private static bool RunImportMenu(string csvPath)
        {
            var csvAsset = AssetDatabase.LoadAssetAtPath<UnityEngine.Object>(csvPath);
            Assert.IsNotNull(csvAsset, $"csv 必须是已导入的资产: {csvPath}");
            Selection.activeObject = csvAsset;
            return EditorApplication.ExecuteMenuItem(ImportMenu);
        }

        [Test]
        public void FullChain_WaveCsv_MenuEntry_CreatesAssetAtDefaultPath_AndConfigServiceReadsIt()
        {
            // 路径完全由产品代码给出：本用例不出现任何手写资产路径。
            var assetPath = CsvExporter.TableAssetPathFor(WaveCsv);
            Assert.AreEqual("Assets/Configs/CFG_WaveTable.asset", assetPath, "菜单默认路径必须是规范化路径");
            AssetDatabase.DeleteAsset(assetPath); // 上次失败残留
            _tempAssets.Add(assetPath);
            Assert.IsNull(AssetDatabase.LoadAssetAtPath<ScriptableObject>(assetPath), "起点必须是「资产不存在」分支");

            Assert.IsTrue(RunImportMenu(WaveCsv),
                "菜单项 '" + ImportMenu + "' 必须存在、通过校验且不抛（Selection 已指向 wave.csv）");

            var table = AssetDatabase.LoadAssetAtPath<WaveConfigTable>(assetPath);
            Assert.IsNotNull(table, "菜单必须按默认路径建出表资产（旧实现路径含 '..'，Load 恒 null 且清空同名资产）");
            Assert.AreEqual(3, table.Rows.Count, "wave.csv 的三行都应导入");

            var service = new ConfigService();
            service.Load(table);
            var boss = service.Get<WaveConfigRow>("w3");
            Assert.IsNotNull(boss, "导入后 ConfigService 必须能按 Id 读到行");
            Assert.AreEqual(12, boss.Count);
            Assert.AreEqual(4f, boss.Interval, 1e-6f);
            Assert.IsTrue(boss.Boss);
        }

        [Test]
        public void FullChain_WaveCsv_MenuEntry_DoesNotWipeExistingTable()
        {
            var assetPath = CsvExporter.TableAssetPathFor(WaveCsv);
            AssetDatabase.DeleteAsset(assetPath);
            _tempAssets.Add(assetPath);

            // 预置一张「同名」表：菜单再导入同一 CSV 时不得把这张表清空/换 GUID。
            var seeded = ScriptableObject.CreateInstance<WaveConfigTable>();
            seeded.AddRow(new WaveConfigRow { Id = "keep_me", Count = 77, Interval = 2.5f, Boss = true });
            AssetDatabase.CreateAsset(seeded, assetPath);
            AssetDatabase.SaveAssets();
            var guidBefore = AssetDatabase.AssetPathToGUID(assetPath);
            Assert.IsFalse(string.IsNullOrEmpty(guidBefore), "预置资产必须有 GUID");

            Assert.IsTrue(RunImportMenu(WaveCsv), "既有资产上跑菜单不得抛异常");

            var table = AssetDatabase.LoadAssetAtPath<WaveConfigTable>(assetPath);
            Assert.IsNotNull(table, "既有表资产必须仍然存在且可 Load（不得先建后毁）");
            Assert.AreEqual(guidBefore, AssetDatabase.AssetPathToGUID(assetPath),
                "就地更新：GUID 不变（DeleteAsset+CreateAsset 会换 GUID 并打断引用）");
            Assert.AreEqual(4, table.Rows.Count, "3 行来自 csv + 1 行预置；预置行不得丢失");

            WaveConfigRow kept = null;
            foreach (var row in table.Rows)
            {
                if (row.Id == "keep_me")
                {
                    kept = row;
                }
            }

            Assert.IsNotNull(kept, "预置行 keep_me 必须仍在表里");
            Assert.AreEqual(77, kept.Count, "既有行内容不得被清空");
            Assert.AreEqual(2.5f, kept.Interval, 1e-6f);
            Assert.IsTrue(kept.Boss);

            var service = new ConfigService();
            service.Load(table);
            Assert.AreEqual(12, service.Get<WaveConfigRow>("w3").Count, "csv 行必须真正写入同一张表");
        }

        [Test]
        public void ImportRegisteredCsv_DefaultPath_IsNormalized_AndCreatesAsset()
        {
            // 程序化入口（不传路径）也必须落到规范化默认路径，而不是 "CSV/../"。
            var assetPath = CsvExporter.TableAssetPathFor(WaveCsv);
            AssetDatabase.DeleteAsset(assetPath);
            _tempAssets.Add(assetPath);

            var report = CsvImporter.ImportRegisteredCsv(WaveCsv);

            Assert.IsTrue(report.Ok, string.Join("; ", report.Errors));
            Assert.AreEqual(3, report.Added);
            Assert.IsNotNull(AssetDatabase.LoadAssetAtPath<WaveConfigTable>(assetPath),
                "不传路径时必须建在 TableAssetPathFor 的默认（规范化）位置");
        }

