using System;
using System.Threading.Tasks;
using UnityEngine;
using UnityEngine.Audio;
using ZFrame.Core;
using ZFrame.Data;

namespace ZFrame.View
{
    /// <summary>
    /// Audio service adapter (TASK-A-M2-02): MonoBehaviour front end over the
    /// pure C# core pieces (<see cref="AudioMath"/>, <see cref="CrossfadeState"/>,
    /// <see cref="SfxLimiter"/>). Registered in <see cref="Services"/> as
    /// <see cref="IAudioService"/>; its Tick runs on the central game loop via
    /// <see cref="ITickQueue"/> (registered at <see cref="TickStage.View"/>) —
    /// it never implements Update: the frame order stays GameLoopDriver-owned.
    ///
    /// Drive chain: GameLoopDriver.Update → TickQueue.TickAll(View) →
    /// AudioService.Tick(dt) → CrossfadeState weights → BGM track volumes;
    /// SfxLimiter.BeginFrame resets the per-frame SFX budget.
    ///
    /// Sources: 2 BGM AudioSources (equal-power crossfade pair, looped) and a
    /// 12-slot SFX pool (simple round-robin internal pool — chosen over
    /// PoolRegistry/ComponentPool because pool entries here are plain
    /// AudioSources created once at Init, not prefab instances, and the pool
    /// needs an "oldest steal" strategy, not spawn/despawn semantics; see
    /// 施工报告). Clips load through <see cref="IResourceService"/> with the
    /// bgm_/sfx_ key convention; missing assets LogWarn and never throw.
    ///
    /// MOUNTING: self-bootstraps via <see cref="RuntimeInitializeOnLoadMethod"/>
    /// (BeforeSceneLoad) onto its own DontDestroyOnLoad host "~AudioRoot",
    /// same pattern as SceneLoader/DebugPanelRoot — Core never references View.
    /// The AudioMixer (Assets/Audio/MIX_AudioMixer.asset, generated by
    /// ZFrame.View.AudioMixerSetup) is optional at boot: without it bus
    /// volumes are cached and applied as soon as <see cref="SetMixer"/> is
    /// called by scene wiring (M4); runtime mixer lookup via Resources is
    /// attempted as a convenience.
    /// </summary>
    [DisallowMultipleComponent]
    public sealed class AudioService : MonoBehaviour, IAudioService, ITickable
    {
        private const string LogChannel = "Audio";

        /// <summary>BGM crossfade track count (fixed pair).</summary>
        public const int BgmTrackCount = 2;

        /// <summary>SFX source pool size (方案 §6.6).</summary>
        public const int SfxPoolSize = 12;

        /// <summary>Maximum SFX plays allowed through per frame.</summary>
        public const int MaxSfxPerFrame = 4;

        /// <summary>Resource key prefix for music loops.</summary>
        public const string BgmKeyPrefix = "bgm_";

        /// <summary>Resource key prefix for one-shot effects.</summary>
        public const string SfxKeyPrefix = "sfx_";

        private static AudioService _instance;

        /// <summary>The self-bootstrapped instance (null before boot).</summary>
        public static AudioService Instance => _instance;

        private readonly CrossfadeState _crossfade = new CrossfadeState();
        private readonly SfxLimiter _limiter = new SfxLimiter(MaxSfxPerFrame);
        private readonly float[] _busVolumes = { 1f, 1f, 1f, 1f };
        private readonly string[] _bgmKeys = new string[BgmTrackCount];

        private AudioMixer _mixer;
        private AudioMixerGroup _bgmGroup;
        private AudioMixerGroup _sfxGroup;
        private AudioMixerGroup _uiGroup;
        private AudioSource[] _bgmTracks;
        private AudioSource[] _sfxPool;
        private int _sfxNext;
        private bool _initialized;

        /// <summary>
        /// Self-bootstrap: creates the DontDestroyOnLoad host before the first
        /// scene loads and wires the loop + service registrations.
        /// </summary>
        [RuntimeInitializeOnLoadMethod(RuntimeInitializeLoadType.BeforeSceneLoad)]
        private static void AutoBoot()
        {
            if (_instance != null)
            {
                return;
            }

            var host = new GameObject("~AudioRoot");
            DontDestroyOnLoad(host);
            host.AddComponent<AudioService>().Initialize(FindBootMixer());
        }

        /// <summary>
        /// Convenience runtime lookup of the mixer asset. Returns null (with a
        /// log) when the asset is not under a Resources folder — scene wiring
        /// then assigns it via <see cref="SetMixer"/>.
        /// </summary>
        public static AudioMixer FindBootMixer()
        {
            var mixer = Resources.Load<AudioMixer>("MIX_AudioMixer");
            if (mixer == null)
            {
                ZLog.Info(LogChannel,
                    "AudioService: MIX_AudioMixer not found via Resources; bus volumes will be " +
                    "cached until scene wiring calls SetMixer (asset lives at Assets/Audio/).");
            }

            return mixer;
        }

        /// <summary>
        /// Builds sources, registers into <see cref="Services"/> as
        /// <see cref="IAudioService"/> and into the game loop via
        /// <see cref="ITickQueue"/> at the View stage. Idempotent; the loop
        /// services are guaranteed via <see cref="GameRoot.EnsureInstance"/>
        /// (which is safe both in play mode and EditMode). Call once after
        /// AddComponent; <see cref="SetMixer"/> may be called before or after.
        /// </summary>
        public void Initialize(AudioMixer mixer)
        {
            if (_initialized)
            {
                return;
            }

            _instance = this;
            _initialized = true;

            if (Services.TryGet(out IAudioService existing) && !ReferenceEquals(existing, this))
            {
                ZLog.Warn(LogChannel,
                    "AudioService: another IAudioService is already registered; the newcomer stays unregistered.");
                return;
            }

            if (_mixer == null)
            {
                SetMixer(mixer);
            }

            BuildSources();

            // Loop guarantee: EnsureInstance bootstraps in play mode (Awake)
            // and, in EditMode tests where Awake never runs, exposes the
            // documented Initialize() seam — IsBootstrapped guards both.
            GameRoot.EnsureInstance();
            if (!GameRoot.IsBootstrapped)
            {
                GameRoot.Instance.Initialize();
            }

            Services.Register<IAudioService>(this);
            Services.Get<ITickQueue>().Register(this, TickStage.View);
        }

        /// <summary>
        /// Attaches (or replaces) the AudioMixer: resolves the BGM/SFX/UI
        /// groups and applies the cached bus volumes immediately. Null-safe —
        /// the service runs mixerless (volumes cached only) until called.
        /// </summary>
        public void SetMixer(AudioMixer mixer)
        {
            _mixer = mixer;
            if (_mixer == null)
            {
                _bgmGroup = _sfxGroup = _uiGroup = null;
                return;
            }

            _bgmGroup = FindGroup(_mixer, "BGM");
            _sfxGroup = FindGroup(_mixer, "SFX");
            _uiGroup = FindGroup(_mixer, "UI");

            // Apply the cached 0..1 volumes through the dB mapping now.
            foreach (AudioBus bus in Enum.GetValues(typeof(AudioBus)))
            {
                SetBusVolume(bus, _busVolumes[(int)bus]);
            }
        }

        /// <inheritdoc/>
        public void PlayBgm(string id, float fade = 0.5f)
        {
            if (string.IsNullOrEmpty(id))
            {
                ZLog.Warn(LogChannel, "PlayBgm: id must not be null/empty.");
                return;
            }

            string key = BgmKeyPrefix + id;
            if (!TryLoadClip(key, out AudioClip clip))
            {
                return; // TryLoadClip already warned
            }

            // Incoming track = the one NOT currently targeted by the fade
            // (i.e. the silent one); the crossfade then heads toward it.
            int incoming = 1 - _crossfade.Target;
            var source = _bgmTracks[incoming];

            ReleaseBgmKey(incoming);
            _bgmKeys[incoming] = key;

            source.clip = clip;
            source.loop = true;
            source.outputAudioMixerGroup = _bgmGroup;
            source.volume = 0f;
            source.Play();

            _crossfade.Start(incoming, fade);
        }

        /// <inheritdoc/>
        public void StopBgm(float fade = 0.5f)
        {
            // Fade toward the OTHER track, whose clip/key are cleared first —
            // the equal-power curve then falls to silence on both audible
            // content paths with no special "fade to zero" state.
            int incoming = 1 - _crossfade.Target;

            ReleaseBgmKey(incoming);
            var source = _bgmTracks[incoming];
            source.Stop();
            source.clip = null;

            _crossfade.Start(incoming, fade);
        }

        /// <inheritdoc/>
        public void PlaySfx(string id, Vector3? worldPos = null)
        {
            if (string.IsNullOrEmpty(id))
            {
                ZLog.Warn(LogChannel, "PlaySfx: id must not be null/empty.");
                return;
            }

            // Rate limiting is intentional BEFORE the (synchronous) load: a
            // rejected play must not pay for asset work.
            if (!_limiter.TryPlay(id))
            {
                return;
            }

            string key = SfxKeyPrefix + id;
            if (!TryLoadClip(key, out AudioClip clip))
            {
                return;
            }

            var source = AcquireSfxSource();
            source.outputAudioMixerGroup = _sfxGroup;
            source.clip = clip;
            source.loop = false;
            source.spatialBlend = worldPos.HasValue ? 1f : 0f;
            if (worldPos.HasValue)
            {
                source.transform.position = worldPos.Value;
            }

            source.volume = 1f;
            source.Play();
        }

        /// <inheritdoc/>
        public void SetBusVolume(AudioBus bus, float volume01)
        {
            _busVolumes[(int)bus] = volume01;

            if (_mixer == null)
            {
                return; // cached; applied when SetMixer arrives
            }

            string param = GetExposedParamName(bus);
            if (!_mixer.SetFloat(param, AudioMath.LinearToDb(volume01)))
            {
                ZLog.Warn(LogChannel, $"SetBusVolume: mixer has no exposed parameter '{param}'.");
            }
        }

        /// <inheritdoc/>
        public float GetBusVolume(AudioBus bus)
        {
            return _busVolumes[(int)bus];
        }

        /// <summary>
        /// Exposed Volume parameter name of a bus — must match the parameters
        /// the AudioMixerSetup generator exposes on MIX_AudioMixer.
        /// </summary>
        public static string GetExposedParamName(AudioBus bus)
        {
            switch (bus)
            {
                case AudioBus.Master: return "MasterVolume";
                case AudioBus.Bgm: return "BGMVolume";
                case AudioBus.Sfx: return "SFXVolume";
                case AudioBus.Ui: return "UIVolume";
                default:
                    throw new ArgumentOutOfRangeException(nameof(bus), bus, "Unknown audio bus.");
            }
        }

        /// <summary>
        /// Game-loop tick (View stage, driven by GameLoopDriver via ITickQueue):
        /// resets the SFX frame budget and applies crossfade weights to the
        /// BGM track volumes. This — not MonoBehaviour.Update — is the single
        /// per-frame entry point.
        /// </summary>
        public void Tick(float dt)
        {
            _limiter.BeginFrame();

            (float weightA, float weightB) = _crossfade.Tick(dt);
            _bgmTracks[0].volume = weightA;
            _bgmTracks[1].volume = weightB;

            // A finished fade leaves the outgoing track at 0 — stop it so the
            // pair never accumulates playing (but muted) sources.
            for (int i = 0; i < BgmTrackCount; i++)
            {
                bool silent = (i == 0 ? weightA : weightB) <= 0.0001f;
                if (silent && _bgmTracks[i].isPlaying && i != _crossfade.Target)
                {
                    _bgmTracks[i].Stop();
                }
            }
        }

        private void BuildSources()
        {
            _bgmTracks = new AudioSource[BgmTrackCount];
            for (int i = 0; i < BgmTrackCount; i++)
            {
                _bgmTracks[i] = CreateChildSource($"BGM_Track{i}");
                _bgmTracks[i].loop = true;
            }

            _sfxPool = new AudioSource[SfxPoolSize];
            for (int i = 0; i < SfxPoolSize; i++)
            {
                _sfxPool[i] = CreateChildSource($"SFX_{i:D2}");
            }
        }

        private AudioSource CreateChildSource(string name)
        {
            var child = new GameObject(name);
            child.transform.SetParent(transform, false);
            var source = child.AddComponent<AudioSource>();
            source.playOnAwake = false;
            return source;
        }

        /// <summary>
        /// Pool pick: first non-playing source from the round-robin cursor;
        /// when all 12 are busy, steal the cursor slot (oldest-first fairness).
        /// </summary>
        private AudioSource AcquireSfxSource()
        {
            for (int i = 0; i < SfxPoolSize; i++)
            {
                int index = (_sfxNext + i) % SfxPoolSize;
                if (!_sfxPool[index].isPlaying)
                {
                    _sfxNext = (index + 1) % SfxPoolSize;
                    return _sfxPool[index];
                }
            }

            int stolen = _sfxNext;
            _sfxNext = (stolen + 1) % SfxPoolSize;
            return _sfxPool[stolen];
        }

        private bool TryLoadClip(string key, out AudioClip clip)
        {
            clip = null;

            if (!Services.TryGet(out IResourceService resources))
            {
                ZLog.Warn(LogChannel,
                    $"TryLoadClip('{key}'): no IResourceService registered — call ZFrameData.Init first.");
                return false;
            }

            Task<AudioClip> task = resources.LoadAsync<AudioClip>(key);
            if (!task.IsCompleted)
            {
                // Current provider is synchronous; an async provider arrives
                // in a later milestone — reject this frame's play rather than
                // queue (SFX one-shots are time-sensitive anyway).
                ZLog.Warn(LogChannel, $"TryLoadClip('{key}'): load still in flight; skipping this play.");
                return false;
            }

            try
            {
                clip = task.Result;
            }
            catch (Exception e) when (e.InnerException != null || e is AggregateException)
            {
                ZLog.Warn(LogChannel, $"TryLoadClip('{key}'): load failed — {e.InnerException?.Message ?? e.Message}");
                return false;
            }

            if (clip == null)
            {
                ZLog.Warn(LogChannel, $"TryLoadClip('{key}'): no AudioClip found (expected under Resources).");
                return false;
            }

            return true;
        }

        private void ReleaseBgmKey(int track)
        {
            string key = _bgmKeys[track];
            if (key != null && Services.TryGet(out IResourceService resources))
            {
                resources.Release(key);
            }

            _bgmKeys[track] = null;
        }

        private static AudioMixerGroup FindGroup(AudioMixer mixer, string name)
        {
            var groups = mixer.FindMatchingGroups(name);
            if (groups == null || groups.Length == 0)
            {
                ZLog.Warn(LogChannel, $"SetMixer: no '{name}' group on '{mixer.name}'.");
                return null;
            }

            // FindMatchingGroups returns partial matches with the most
            // specific first; exact name match wins when present.
            foreach (var group in groups)
            {
                if (group.name == name)
                {
                    return group;
                }
            }

            return groups[0];
        }

        /// <summary>
        /// Deterministic teardown seam (also invoked by <see cref="OnDestroy"/>):
        /// unregisters from the game loop and from
        /// <see cref="Services"/>. Mirrors the GameRoot.Initialize/Shutdown
        /// pattern so EditMode tests — where MonoBehaviour callbacks are not
        /// reliably driven — exercise the exact path the engine runs at
        /// object teardown. Idempotent.
        /// </summary>
        public void Shutdown()
        {
            if (!_initialized)
            {
                return;
            }

            _initialized = false;

            if (_instance == this)
            {
                _instance = null;
            }

            if (Services.TryGet(out ITickQueue queue))
            {
                queue.Unregister(this);
            }

            if (Services.TryGet(out IAudioService service) && ReferenceEquals(service, this))
            {
                Services.Unregister<IAudioService>();
            }
        }

        private void OnDestroy()
        {
            Shutdown();
        }
    }
}
