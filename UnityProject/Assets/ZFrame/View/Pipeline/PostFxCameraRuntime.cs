using UnityEngine;
using UnityEngine.Rendering.Universal;
using UnityEngine.SceneManagement;
using ZFrame.Core;

namespace ZFrame.View
{
    /// <summary>
    /// Runtime seam that finally switches URP camera post-processing ON
    /// (TASK-A-R9-04).
    ///
    /// The defect it repairs: every grade asset was authored and every tier
    /// swap was wired (<see cref="PipelineManager"/> swaps
    /// <c>~GradeVolume.sharedProfile</c>), but <c>SCN_Game</c>'s Main Camera
    /// carries no <see cref="UniversalAdditionalCameraData"/>. URP 14 then takes
    /// the "no additional data" branch and hard-sets
    /// <c>cameraData.postProcessEnabled = false</c>
    /// (UniversalRenderPipeline.cs:1264-1271), and the component's own default
    /// is <c>renderPostProcessing = false</c>
    /// (UniversalAdditionalCameraData.cs:322). Net effect: Bloom /
    /// ColorAdjustments were configuration with zero pixels.
    ///
    /// Why runtime injection instead of editing the scene: project policy
    /// (B-R9-06 / B-R9-08, ZrFrameGenerationFeature.cs:11-12) forbids asset
    /// pollution, and the scene is regenerated by tools. URP only reads this
    /// flag through the component, so adding the component in code is enough —
    /// no .unity/.asset write is required.
    ///
    /// Scope: cameras of type <see cref="CameraType.Game"/> that exist when a
    /// scene finishes loading (or when <see cref="ApplyToAllCameras"/> is
    /// called explicitly). Cameras spawned later are covered as soon as the
    /// owning system calls <see cref="ApplyToAllCameras"/> — this type
    /// deliberately does NOT hook per-frame callbacks, so an offscreen/bench
    /// camera that sets its own flag keeps control (ParityBench.cs:157-158
    /// still owns "post processing off" for the parity contract).
    /// </summary>
    public static class PostFxCameraRuntime
    {
        private const string LogChannel = "Pipeline";

        private static bool _enabled = true;
        private static bool _hooked;

        /// <summary>True while the seam keeps <c>renderPostProcessing</c> on.</summary>
        public static bool IsEnabled => _enabled;

        /// <summary>Cameras the last <see cref="ApplyToAllCameras"/> pass touched.</summary>
        public static int AppliedCameraCount { get; private set; }

        /// <summary>
        /// Self-bootstrap after the first scene is loaded (the main camera of
        /// that scene must already exist). Keeps following later scene loads.
        /// </summary>
        [RuntimeInitializeOnLoadMethod(RuntimeInitializeLoadType.AfterSceneLoad)]
        private static void AutoBoot()
        {
            Hook();
            ApplyToAllCameras();
        }

        private static void Hook()
        {
            if (_hooked)
            {
                return;
            }

            SceneManager.sceneLoaded += OnSceneLoaded;
            _hooked = true;
        }

        private static void OnSceneLoaded(Scene scene, LoadSceneMode mode)
        {
            ApplyToAllCameras();
        }

        /// <summary>
        /// Turns the seam on/off for every game camera and applies it now.
        /// Idempotent; used by the pipeline tests as the on/off seam.
        /// </summary>
        public static void SetEnabled(bool enabled)
        {
            _enabled = enabled;
            ApplyToAllCameras();
        }

        /// <summary>Applies <see cref="IsEnabled"/> to every loaded game camera, returns the count.</summary>
        public static int ApplyToAllCameras()
        {
            Camera[] cameras = Object.FindObjectsOfType<Camera>(true);
            int applied = 0;
            for (int i = 0; i < cameras.Length; i++)
            {
                if (Apply(cameras[i]))
                {
                    applied++;
                }
            }

            AppliedCameraCount = applied;
            if (applied > 0 && _enabled)
            {
                ZLog.Info(LogChannel, $"camera post-processing enabled on {applied} camera(s) (URP renderPostProcessing)");
            }

            return applied;
        }

        /// <summary>
        /// Ensures <paramref name="camera"/> owns a
        /// <see cref="UniversalAdditionalCameraData"/> and mirrors
        /// <see cref="IsEnabled"/> onto it. Returns false for non-game cameras
        /// (preview/reflection/UI-preview) so nothing else is disturbed.
        /// </summary>
        public static bool Apply(Camera camera)
        {
            if (camera == null || camera.cameraType != CameraType.Game)
            {
                return false;
            }

            UniversalAdditionalCameraData data = camera.GetUniversalAdditionalCameraData();
            data.renderPostProcessing = _enabled;
            return true;
        }

        /// <summary>True when the camera physically carries the URP component (the shipped defect check).</summary>
        public static bool HasCameraData(Camera camera)
        {
            return camera != null && camera.TryGetComponent(out UniversalAdditionalCameraData _);
        }

        /// <summary>True when the component exists AND its post-processing flag is on.</summary>
        public static bool IsPostProcessingOn(Camera camera)
        {
            return camera != null
                   && camera.TryGetComponent(out UniversalAdditionalCameraData data)
                   && data.renderPostProcessing;
        }
    }
}
